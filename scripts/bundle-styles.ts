#!/usr/bin/env bun
/** Canonical readable CSS → the same budgeted/served public/styles.css URL. */
import { join } from "node:path";
import { writeFileSync } from "node:fs";

const ROOT = join(import.meta.dirname, "..");
export async function buildStylesheet(source = join(ROOT, "src/browser/styles.css")): Promise<string> {
  const result = await Bun.build({ entrypoints: [source], target: "browser", minify: true, sourcemap: "none",
    plugins: [{ name: "public-style-resources", setup(build) {
      build.onResolve({ filter: /^\/(?!\/)/ }, args => {
        // Preserve browser-root image/font URLs, not entrypoints or @imports.
        // A broad external glob also hides relative imports after resolution.
        if (args.importer && args.kind !== "import-rule") return { path: args.path, external: true };
      });
    } }],
  });
  if (!result.success || result.logs.length !== 0 || result.outputs.length !== 1 || result.outputs[0]?.loader !== "css") {
    throw new Error(`stylesheet build requires one standalone CSS output with no diagnostics; keep resource URLs explicitly public: ${result.logs.map(String).join("\n")}`);
  }
  return `/* AUTO-GENERATED by scripts/bundle-styles.ts; edit src/browser/styles.css. */\n${(await result.outputs[0].text()).trim()}\n`;
}

if (import.meta.main) {
  const css = await buildStylesheet();
  const out = join(ROOT, "public/styles.css");
  writeFileSync(out, css);
  console.log(`bundled styles → ${out} (${Buffer.byteLength(css)} bytes)`);
}
