#!/usr/bin/env bun
/**
 * Bundles public/app.ts into public/app.bundle.js for browser consumption.
 * Uses Bun.build() with browser target and IIFE output so app internals do not
 * become mutable window properties.
 *
 * Output: public/app.bundle.js
 *
 * Usage in HTML:
 *   <script src="/app.bundle.js"></script>
 */
import { join } from "node:path";
import { writeFileSync, existsSync } from "node:fs";
import { APP_MINIFIER_VERSION, minifyBrowserIife } from "./minify-browser-iife.ts";

const ROOT = join(import.meta.dirname, "..");
const ENTRY = join(ROOT, "public", "app.ts");
const OUT_PATH = join(ROOT, "public", "app.bundle.js");

/** The canonical bytes, also used by owned browser fixtures; no public-file writes. */
export async function buildAppBundle(): Promise<string> {
  const result = await Bun.build({
    entrypoints: [ENTRY],
    target: "browser",
    format: "iife",
    // IIFE identifiers are private; public property names and window hooks remain.
    // Internal diagnostic names are minified (Bun 1.4.2 ignores keepNames here).
    minify: { whitespace: true, syntax: true, identifiers: true },
  });
  if (!result.success || result.outputs.length !== 1) {
    throw new Error(`bundle-app failed: ${result.logs.map(String).join("\n") || "expected one browser IIFE"}`);
  }
  const code = await minifyBrowserIife((await result.outputs[0].text()).trim());
  return `// AUTO-GENERATED by scripts/bundle-app.ts (Bun + Terser ${APP_MINIFIER_VERSION}) — do not edit
${code}
`;
}

if (import.meta.main) {
  if (!existsSync(ENTRY)) {
    console.error(`bundle-app: ${ENTRY} not found — skipping`);
    process.exit(0);
  }
  const bundle = await buildAppBundle();
  writeFileSync(OUT_PATH, bundle);
  const sizeKB = (Buffer.byteLength(bundle) / 1024).toFixed(1);
  console.log(`bundled app → ${OUT_PATH} (${sizeKB} KB)`);
}
